import com.example.core.model.ThemeMode

private val FamilyLightColorScheme = lightColorScheme(
    primary = EmeraldPrimary,
    onPrimary = OnEmeraldPrimary,
    primaryContainer = EmeraldContainer,
    onPrimaryContainer = OnEmeraldContainer,
    secondary = JadeSecondary,
    onSecondary = OnJadeSecondary,
    secondaryContainer = JadeContainer,
    onSecondaryContainer = OnJadeContainer,
    tertiary = WealthGoldTertiary,
    onTertiary = OnWealthGoldTertiary,
    tertiaryContainer = WealthGoldContainer,
    onTertiaryContainer = OnWealthGoldContainer,
    background = LightBackground,
    onBackground = LightOnBackground,
    surface = LightSurface,
    onSurface = LightOnSurface,
    surfaceVariant = LightSurfaceVariant,
    onSurfaceVariant = LightOnSurfaceVariant,
    surfaceContainerLow = LightSurfaceContainerLow,
    surfaceContainer = LightSurfaceContainer,
    surfaceContainerHigh = LightSurfaceContainerHigh,
    outline = LightOutline,
    outlineVariant = LightOutlineVariant
)

private val FamilyDarkColorScheme = darkColorScheme(
    primary = DarkEmeraldPrimary,
    onPrimary = DarkOnEmeraldPrimary,
    primaryContainer = DarkEmeraldContainer,
    onPrimaryContainer = DarkOnEmeraldContainer,
    secondary = DarkJadeSecondary,
    onSecondary = DarkOnJadeSecondary,
    secondaryContainer = DarkJadeContainer,
    onSecondaryContainer = DarkOnJadeContainer,
    tertiary = DarkWealthGoldTertiary,
    onTertiary = DarkOnWealthGoldTertiary,
    tertiaryContainer = DarkWealthGoldContainer,
    onTertiaryContainer = DarkOnWealthGoldContainer,
    background = DarkBackground,
